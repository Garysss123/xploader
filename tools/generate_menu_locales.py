"""Generate bounded UTF-8 catalogs and 24px OFL glyphs for native C code."""
import hashlib,json
from PIL import Image,ImageDraw,ImageFont
from native_menu_device import ROOT
base=ROOT/'src/menu';fontbase=ROOT/'artifacts/menu-font-source-002';meta=json.loads((fontbase/'source.json').read_text())
fontpath=fontbase/'NotoSansTC-VF.ttf'
if hashlib.sha256(fontpath.read_bytes()).hexdigest()!=meta['font_sha256']:raise RuntimeError('Pinned font source differs')
en=json.loads((base/'catalogs/en.json').read_text(encoding='utf-8'));zh=json.loads((base/'catalogs/zh-TW.json').read_text(encoding='utf-8'))
if en['messages'].keys()!=zh['messages'].keys():raise RuntimeError('Catalog message IDs must agree')
keys=list(en['messages']);codepoints=sorted({ord(c) for s in [zh['name'],*zh['messages'].values()] for c in s if ord(c)>126})
edge=24;font=ImageFont.truetype(str(fontpath),edge);font.set_variation_by_axes([400])
lines=['/* Generated by tools/generate_menu_locales.py; font licensed under OFL. */','#ifndef XPL_LOCALE_DATA_H','#define XPL_LOCALE_DATA_H','typedef struct {const char *id,*en,*zh;} xpl_locale_entry;','static const xpl_locale_entry xpl_locale_entries[]={']
for key in keys:
    row=','.join(json.dumps(x,ensure_ascii=False) for x in [key,en['messages'][key],zh['messages'][key]])
    lines.append('    {'+row+'},')
lines+=['};','static const xpl_cjk_glyph xpl_cjk_glyphs[]={']
for cp in codepoints:
    im=Image.new('L',(edge,edge));draw=ImageDraw.Draw(im);draw.text((0,0),chr(cp),font=font,fill=255,anchor='lt')
    rows=[]
    for y in range(edge):rows.append(sum((1<<(edge-1-x)) for x in range(edge) if im.getpixel((x,y))>=128))
    if not any(rows) and cp!=0x3000:raise RuntimeError('Empty catalog glyph '+hex(cp))
    lines.append('    {0x%xu,{%s}},'%(cp,','.join('0x%08x'%r for r in rows)))
lines+=['};','#endif','']
target=base/'xpl_locale_data.h'
if target.exists() and not target.read_text(encoding='utf-8').startswith('/* Generated by tools/generate_menu_locales.py;'):raise RuntimeError('Preserve non-generated locale file')
target.write_text('\n'.join(lines),encoding='utf-8')
license_dir=base/'fonts';license_dir.mkdir(exist_ok=True);(license_dir/'OFL.txt').write_bytes((fontbase/'OFL.txt').read_bytes())
(license_dir/'source.json').write_text(json.dumps({'source':meta,'catalog_glyph_count':len(codepoints),'bitmap_height':edge,'bitmap_glyph_bytes':4*(edge+1),'generator':'tools/generate_menu_locales.py','generated_sha256':hashlib.sha256(target.read_bytes()).hexdigest()},indent=2)+'\n',encoding='utf-8')
print('Catalogs:',len(keys),'TC glyphs:',len(codepoints),'bitmap data bytes:',len(codepoints)*4*(edge+1))
